"""The 3.0 documentation: the vector flow diagram, the screenshots the docs embed, and the demo project behind them.

Run: python3 -I -m unittest discover -s skills/core/tests -p test_v3_docs.py -v
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import tempfile
import unittest
import xml.etree.ElementTree as ET
from pathlib import Path

CORE = Path(__file__).resolve().parent.parent
KIT = CORE.parent.parent
REPO = KIT.parent.parent.parent
DOCS = KIT / "docs"
sys.path.insert(0, str(CORE / "scripts"))
SVG = "{http://www.w3.org/2000/svg}"


class TestFlowDiagram(unittest.TestCase):
    def setUp(self) -> None:
        self.path = DOCS / "dev-kit-flow.svg"
        self.root = ET.parse(self.path).getroot()

    def test_is_a_true_vector_that_scales(self) -> None:
        self.assertEqual(self.root.tag, SVG + "svg")
        self.assertRegex(self.root.get("viewBox", ""), r"^0 0 \d+ \d+$")
        self.assertIsNone(self.root.get("width"))  # no fixed size: it scales to its container
        self.assertIsNone(self.root.get("height"))
        self.assertEqual(list(self.root.iter(SVG + "image")), [])  # nothing embedded as a raster
        self.assertNotIn("data:image", self.path.read_text(encoding="utf-8"))
        self.assertNotIn("Generated by graphviz", self.path.read_text(encoding="utf-8"))

    def test_text_is_text_and_covers_the_whole_flow(self) -> None:
        words = " ".join("".join(t.itertext()) for t in self.root.iter(SVG + "text"))
        for step in ("interview", "PRD", "architecture", "plan", "implement", "QA", "gate passed?", "release review",
                     "your approval", "production", "released", "stable", "production health", "/dev-kit:issue"):
            self.assertIn(step, words)
        self.assertTrue(self.root.find(SVG + "title").text)
        self.assertGreater(len(self.root.find(SVG + "desc").text), 200)  # the alt text for screen readers

    def test_has_a_dark_variant(self) -> None:
        style = "".join(self.root.find(SVG + "style").itertext())
        self.assertIn("prefers-color-scheme: dark", style)

    def test_the_old_graphviz_files_are_gone_and_nobody_links_them(self) -> None:
        self.assertFalse((DOCS / "dev-kit-flow.dot").exists())
        self.assertFalse((DOCS / "dev-kit-flow.png").exists())
        for md in [*KIT.rglob("*.md"), REPO / "README.md", REPO / "GET_STARTED.md"]:
            if md.name == "CHANGELOG.md":
                continue
            self.assertNotIn("dev-kit-flow.png", md.read_text(encoding="utf-8"), md)
            self.assertNotIn("dev-kit-flow.dot", md.read_text(encoding="utf-8"), md)


class TestDocImages(unittest.TestCase):
    def test_every_image_the_docs_embed_exists(self) -> None:
        pages = [REPO / "README.md", REPO / "GET_STARTED.md", KIT / "README.md", *DOCS.glob("*.md")]
        seen = 0
        for page in pages:
            text = page.read_text(encoding="utf-8")
            for ref in re.findall(r'(?:src|srcset)="([^"]+\.(?:png|svg))"|!\[[^\]]*\]\(([^)]+\.(?:png|svg))\)', text):
                ref = ref[0] or ref[1]
                self.assertTrue((page.parent / ref).is_file(), f"{page.name}: {ref}")
                seen += 1
        self.assertGreaterEqual(seen, 10)

    def test_the_screenshots_are_embedded_somewhere(self) -> None:
        text = "".join(p.read_text(encoding="utf-8") for p in [REPO / "GET_STARTED.md", DOCS / "getting-started.md", DOCS / "stages.md"])
        for img in (DOCS / "images").glob("*.png"):
            self.assertIn(f"images/{img.name}", text)


class TestStagesGuide(unittest.TestCase):
    """docs/stages.md walks through every stage of the flow, and says what each one expects from the user."""

    def test_every_stage_has_its_how_to(self) -> None:
        text = (DOCS / "stages.md").read_text(encoding="utf-8")
        sections = re.split(r"^## ", text, flags=re.M)
        stages = {s.split("\n", 1)[0]: s for s in sections[1:]}
        for title in ("1. Conception", "2. Planning", "3. Milestones", "4. Releases", "5. Stable and maintenance", "6. Coming from dev-kit 2.x"):
            self.assertIn(title, stages)
        for title in ("1. Conception", "2. Planning", "3. Milestones", "4. Releases", "5. Stable and maintenance"):
            for part in ("**Run**", "**The board shows**", "**Needs you**", "**Unstuck**"):
                self.assertIn(part, stages[title], f"{title}: {part}")

    def test_the_autopilot_states_match_the_board(self) -> None:
        text = (DOCS / "stages.md").read_text(encoding="utf-8")
        js = (CORE / "shared" / "board" / "board.js").read_text(encoding="utf-8")
        words = re.search(r"const AP_WORD = tmap\(\{(.*?)\}\);", js, re.S).group(1)
        for word in re.findall(r'N_\("([^"]+)"\)', words):
            self.assertIn(word, text, f"stages.md does not explain the Autopilot state '{word}'")

    def test_linked_from_the_entry_points(self) -> None:
        for page in (REPO / "README.md", REPO / "GET_STARTED.md", KIT / "README.md", DOCS / "getting-started.md"):
            self.assertIn("stages.md", page.read_text(encoding="utf-8"), page.name)


class TestDemoProject(unittest.TestCase):
    """The fictional project behind the screenshots is built only through the kit's scripts, so it must keep building."""

    def test_builds_and_the_board_shows_releases_flags_and_health(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "larder"
            env = {k: v for k, v in os.environ.items() if k not in ("DEV_KIT_NOW", "CLAUDE_CODE_SESSION_ID")}
            p = subprocess.run([sys.executable, "-I", str(DOCS / "demo" / "build_demo.py"), str(root)],
                               capture_output=True, text=True, env=env)
            self.assertEqual(p.returncode, 0, p.stdout[-2000:] + p.stderr[-2000:])
            st = subprocess.run([sys.executable, "-I", str(CORE / "scripts" / "dev_state.py"), "--root", str(root), "status", "--json"],
                                capture_output=True, text=True, env=env)
            rel = {r["id"]: r["status"] for r in json.loads(st.stdout)["lifecycle"]["releases"]}
            self.assertEqual(rel["R1"], "released")
            import dev_board as db
            s = db.build_state(root)
            self.assertEqual(s["phase"], "construction")
            self.assertEqual({f["name"]: f["state"] for f in s["flags"]}["release_R1"], "on")
            self.assertTrue(s["prod_health"]["history"])
            self.assertTrue(s["questions"])


if __name__ == "__main__":
    unittest.main()
