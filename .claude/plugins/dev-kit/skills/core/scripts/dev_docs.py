#!/usr/bin/env python3
"""dev_docs.py - generated reference docs and in-chat help for the dev-kit plugin.

Standard library only. Usage (from anywhere):
  python3 -I dev_docs.py build            write docs/skills.md, docs/agents.md, docs/recipes.md, docs/glossary.md
  python3 -I dev_docs.py check            exit 1 if the catalog and the skills disagree or the generated docs are stale
  python3 -I dev_docs.py help [QUERY...] [--json]
                                          QUERY: empty (skill map) | a skill name | agents | a glossary term | a question

Single source: skills/core/shared/help.json (English only) plus the frontmatter of skills/*/SKILL.md and agents/*.md.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))  # -I drops the script dir
import dev_score  # noqa: E402

KIT = SCRIPTS.parents[2]            # .../dev-kit
CATALOG = SCRIPTS.parent / "shared" / "help.json"
DOCS = KIT / "docs"
GENERATED = ("skills.md", "agents.md", "recipes.md", "glossary.md")
NOTE = "<!-- Generated by skills/core/scripts/dev_docs.py from skills/core/shared/help.json and the skill/agent frontmatter. Do not edit by hand: edit the catalog and run `dev_docs.py build`. -->"
TIER = {"haiku": "speed", "sonnet": "balanced", "opus": "quality"}
SKILL_FIELDS = ("name", "category", "one_line", "when", "args", "examples", "produces", "related")


def frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---", text, re.S)
    out = {}
    for line in (m.group(1).splitlines() if m else []):
        if ":" in line and not line.startswith(" "):
            k, v = line.split(":", 1)
            v = v.strip()
            if len(v) >= 2 and v[0] == v[-1] == '"':
                v = v[1:-1].replace('\\"', '"')
            out[k.strip()] = v
    return out


def load_catalog() -> dict:
    return json.loads(CATALOG.read_text(encoding="utf-8"))


def skill_dirs() -> dict[str, Path]:
    return {p.parent.name: p for p in sorted((KIT / "skills").glob("*/SKILL.md")) if p.parent.name != "core"}


def agent_files() -> dict[str, Path]:
    return {p.stem: p for p in sorted((KIT / "agents").glob("*.md"))}


def mentions(skill: str, agent: str) -> bool:
    p = skill_dirs().get(skill)
    rx = re.compile(r"(?<![\w-])" + re.escape(agent) + r"(?![\w-])")
    return bool(p and rx.search(p.read_text(encoding="utf-8")))


# ---------------------------------------------------------------- rendering

def render_skills(cat: dict) -> str:
    fm = {n: frontmatter(p) for n, p in skill_dirs().items()}
    lines = ["# Skills", "", NOTE, "",
             "Every skill is invoked as `/dev-kit:<name>`. Not sure which one? `/dev-kit:help <your question>`.", ""]
    for c in cat["categories"]:
        rows = [s for s in cat["skills"] if s["category"] == c["id"]]
        if not rows:
            continue
        lines += [f"## {c['title']}", "", "| Skill | What it does |", "|---|---|"]
        lines += [f"| [`{s['name']}`](#{s['name']}) | {s['one_line']} |" for s in rows]
        lines.append("")
    for s in cat["skills"]:
        lines += [f"### {s['name']}", "", s["one_line"], "", f"**When:** {s['when']}", ""]
        hint = fm.get(s["name"], {}).get("argument-hint", "")
        lines += [f"**Usage:** `/dev-kit:{s['name']} {hint}`".rstrip(), ""]
        if s["args"]:
            lines += ["| Argument | Meaning |", "|---|---|"] + [f"| `{a['arg']}` | {a['meaning']} |" for a in s["args"]] + [""]
        lines += ["**Examples:**", ""] + [f"- `{e['command']}`: {e['what']}" for e in s["examples"]] + [""]
        lines += [f"**Produces:** {s['produces']}", "",
                  "**Related:** " + ", ".join(f"[`{r}`](#{r})" for r in s["related"]), ""]
    return "\n".join(lines).rstrip() + "\n"


def render_agents(cat: dict) -> str:
    lines = ["# Agents", "", NOTE, "",
             "Agents are called by the skills, never directly. Reviewers are read-only and return findings in the same JSON contract; "
             "the score dimension feeds `dev_score.py`. Tier, model and effort are the base of round 1 (conventions.md §9).", "",
             "| Agent | Role | Tier (model / effort) | Score dimension | Called by |", "|---|---|---|---|---|"]
    for name, p in agent_files().items():
        f = frontmatter(p)
        role = re.split(r"(?<=\.)\s", f.get("description", ""), maxsplit=1)[0]
        model = f.get("model", "inherit")
        dim = dev_score.AUDITOR_DIMENSION.get(name, "not scored")
        by = ", ".join(f"`{c}`" for c in cat.get("agents_called_by", {}).get(name, [])) or "-"
        lines.append(f"| `{name}` | {role} | {TIER.get(model, model)} ({model} / {f.get('effort', '-')}) | {dim} | {by} |")
    return "\n".join(lines) + "\n"


def render_recipes(cat: dict) -> str:
    lines = ["# Recipes", "", NOTE, "", "Short answers to \"how do I…?\". In Claude Code, ask `/dev-kit:help <question>`.", ""]
    for r in cat["recipes"]:
        lines += [f"## {r['title']}", ""] + [f"{i}. {st}" for i, st in enumerate(r["steps"], 1)] + [""]
    return "\n".join(lines).rstrip() + "\n"


def render_glossary(cat: dict) -> str:
    lines = ["# Glossary", "", NOTE, "", "| Term | Meaning |", "|---|---|"]
    lines += [f"| **{g['term']}** | {g['definition']} |" for g in sorted(cat["glossary"], key=lambda g: g["term"].lower())]
    return "\n".join(lines) + "\n"


def rendered(cat: dict) -> dict[str, str]:
    return {"skills.md": render_skills(cat), "agents.md": render_agents(cat),
            "recipes.md": render_recipes(cat), "glossary.md": render_glossary(cat)}


# ---------------------------------------------------------------- check

def problems(cat: dict) -> list[str]:
    out = []
    names = [s.get("name") for s in cat.get("skills", [])]
    real = set(skill_dirs())
    cats = {c["id"] for c in cat.get("categories", [])}
    for n in sorted(real - set(names)):
        out.append(f"skill '{n}' has no entry in help.json")
    for n in sorted(set(names) - real):
        out.append(f"help.json describes '{n}', which is not a skill")
    for s in cat.get("skills", []):
        miss = [f for f in SKILL_FIELDS if not s.get(f) and f != "args"]
        if miss:
            out.append(f"{s.get('name')}: missing {', '.join(miss)}")
        if s.get("category") not in cats:
            out.append(f"{s.get('name')}: unknown category {s.get('category')}")
        for r in s.get("related", []):
            if r not in real:
                out.append(f"{s.get('name')}: related skill '{r}' does not exist")
        for e in s.get("examples", []):
            if not str(e.get("command", "")).startswith(f"/dev-kit:{s.get('name')}"):
                out.append(f"{s.get('name')}: example '{e.get('command')}' does not use /dev-kit:{s.get('name')}")
    agents = set(agent_files())
    declared = cat.get("agents_called_by", {})
    for a in sorted(agents - set(declared)):
        out.append(f"agent '{a}' has no agents_called_by entry in help.json")
    for a, skills_ in declared.items():
        if a not in agents:
            out.append(f"agents_called_by names '{a}', which is not an agent")
        for s in skills_:
            if not mentions(s, a):
                out.append(f"agents_called_by: skill '{s}' never mentions agent '{a}'")
    for r in cat.get("recipes", []):
        for m in re.findall(r"/dev-kit:([a-z]+)", " ".join(r.get("steps", []))):
            if m not in real:
                out.append(f"recipe '{r.get('id')}' points to unknown skill '{m}'")
    for fname, text in rendered(cat).items():
        p = DOCS / fname
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            out.append(f"docs/{fname} is stale: run dev_docs.py build")
    return out


# ---------------------------------------------------------------- help

def words(s: str) -> set[str]:
    return set(re.findall(r"[a-z0-9-]+", s.lower()))


def answer(cat: dict, query: str) -> dict:
    q = query.strip().lower()
    skills = {s["name"]: s for s in cat["skills"]}
    if not q:
        return {"kind": "map", "categories": [
            {"title": c["title"], "skills": [{"name": s["name"], "one_line": s["one_line"]} for s in cat["skills"] if s["category"] == c["id"]]}
            for c in cat["categories"]]}
    first = q.split()[0].removeprefix("/dev-kit:")
    if first in skills and len(q.split()) <= 2:
        s = skills[first]
        hint = frontmatter(skill_dirs()[first]).get("argument-hint", "") if first in skill_dirs() else ""
        return {"kind": "skill", "usage": f"/dev-kit:{first} {hint}".rstrip(), **s}
    if first in ("agents", "agent"):
        return {"kind": "agents", "markdown": render_agents(cat)}
    for g in cat["glossary"]:
        if q in (g["term"].lower(), f"concepts {g['term'].lower()}", f"what is {g['term'].lower()}"):
            return {"kind": "term", **g}
    qw = words(q)
    best, score = None, 0
    for r in cat["recipes"]:
        sc = sum(3 for t in r["topics"] if t in q) + len(qw & words(r["title"]))
        if sc > score:
            best, score = r, sc
    term = next((g for g in cat["glossary"] if g["term"].lower() in q), None)
    if best and score >= 2:
        return {"kind": "recipe", **best, **({"term": term} if term else {})}
    if term:
        return {"kind": "term", **term}
    ranked = sorted(cat["skills"], key=lambda s: -len(qw & words(s["one_line"] + " " + s["when"])))
    return {"kind": "suggest", "skills": [{"name": s["name"], "one_line": s["one_line"]} for s in ranked[:3]],
            "docs": ["docs/recipes.md", "docs/skills.md", "docs/concepts.md", "docs/glossary.md"]}


def render_answer(a: dict) -> str:
    k = a["kind"]
    if k == "map":
        out = []
        for c in a["categories"]:
            out.append(f"{c['title']}:")
            out += [f"  /dev-kit:{s['name']:<13} {s['one_line']}" for s in c["skills"]]
        return "\n".join(out)
    if k == "skill":
        out = [f"/dev-kit:{a['name']} — {a['one_line']}", f"When: {a['when']}", f"Usage: {a['usage']}"]
        out += [f"  {x['arg']}: {x['meaning']}" for x in a["args"]]
        out += ["Examples:"] + [f"  {e['command']}   # {e['what']}" for e in a["examples"]]
        out += [f"Produces: {a['produces']}", "Related: " + ", ".join(a["related"])]
        return "\n".join(out)
    if k == "agents":
        return a["markdown"]
    if k == "term":
        return f"{a['term']}: {a['definition']}"
    if k == "recipe":
        return "\n".join([a["title"]] + [f"  {i}. {s}" for i, s in enumerate(a["steps"], 1)])
    return "No exact match. Closest skills:\n" + "\n".join(f"  /dev-kit:{s['name']}: {s['one_line']}" for s in a["skills"]) + \
        "\nSee " + ", ".join(a["docs"])


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    sub.add_parser("check")
    h = sub.add_parser("help"); h.add_argument("query", nargs="*"); h.add_argument("--json", action="store_true")
    a = p.parse_args(argv)
    cat = load_catalog()
    if a.cmd == "build":
        DOCS.mkdir(parents=True, exist_ok=True)
        for fname, text in rendered(cat).items():
            (DOCS / fname).write_text(text, encoding="utf-8")
            print(f"wrote docs/{fname}")
        rest = [x for x in problems(cat) if "is stale" not in x]
        for x in rest:
            print(f"warning: {x}", file=sys.stderr)
        return 0
    if a.cmd == "check":
        probs = problems(cat)
        for x in probs:
            print(x)
        return 1 if probs else 0
    ans = answer(cat, " ".join(a.query))
    print(json.dumps(ans, indent=2, ensure_ascii=False) if a.json else render_answer(ans))
    return 0


if __name__ == "__main__":
    sys.exit(main())
